import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

function sqlText(value) {
  if (value === null || value === undefined) return 'null'
  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlBool(value) {
  return value ? 'true' : 'false'
}

function sqlNumber(value) {
  if (value === null || value === undefined || Number.isNaN(Number(value))) return 'null'
  return String(Number(value))
}

function sqlJson(value) {
  return `${sqlText(JSON.stringify(value ?? null))}::jsonb`
}

function sqlTextArray(values) {
  const list = Array.isArray(values) ? values : []
  if (!list.length) return `'{}'::text[]`
  return `array[${list.map(sqlText).join(',')}]::text[]`
}

function valuesStatement(table, columns, rows, conflict) {
  if (!rows.length) return ''
  const values = rows.map((row) => `  (${columns.map((column) => row[column]).join(', ')})`).join(',\n')
  return `insert into public.${table} (${columns.join(', ')}) values\n${values}\n${conflict};\n`
}

export function generateAccreditationSql(dataset) {
  const requirements = [...(dataset.requirements || [])].sort((a, b) => a.id.localeCompare(b.id))
  const questions = [...(dataset.questions || [])].sort((a, b) => a.id.localeCompare(b.id))
  const answerOptions = [...(dataset.answerOptions || [])].sort((a, b) => a.questionId.localeCompare(b.questionId) || a.order - b.order)
  const branchingRules = [...(dataset.branchingRules || [])].sort((a, b) => a.questionId.localeCompare(b.questionId) || a.order - b.order)
  const evidenceCriteria = [...(dataset.evidenceCriteria || [])].sort((a, b) => a.requirementId.localeCompare(b.requirementId) || a.evidenceType.localeCompare(b.evidenceType))
  const sources = [...(dataset.sources || [])].sort((a, b) => a.id.localeCompare(b.id))
  const requirementActive = new Map(requirements.map((item) => [item.id, Boolean(item.active)]))

  const chunks = [
    '-- Generated by scripts/generate-accreditation-sql.mjs. Do not hand-edit.\n',
    `-- Source: ${dataset.meta?.generatedFrom || 'MediQo accreditation dataset'}\n`,
    'begin;\n\n',
  ]

  chunks.push(valuesStatement('accreditation_sources',
    ['id','publisher','title','current_use','url','used_for','verification'],
    sources.map((item) => ({
      id: sqlText(item.id), publisher: sqlText(item.publisher), title: sqlText(item.title), current_use: sqlText(item.currentUse),
      url: sqlText(item.url), used_for: sqlText(item.usedFor), verification: sqlText(item.verification),
    })),
    `on conflict (id) do update set publisher=excluded.publisher,title=excluded.title,current_use=excluded.current_use,url=excluded.url,used_for=excluded.used_for,verification=excluded.verification,updated_at=now()`
  ))

  chunks.push(valuesStatement('accreditation_requirements',
    ['id','standard_version_id','indicator','criterion','criterion_description','classification','classification_source','plain_english_requirement','applicability_rule','primary_readiness_question','assessment_basis','appears_ready_rule','needs_attention_rule','confirmed_gap_rule','not_checked_rule','quick_check_priority','critical_safety_area','national_not_met_count','national_not_met_rank','content_validation_status','content_validation_source','source_urls','source_payload','is_active'],
    requirements.map((item) => ({
      id: sqlText(item.id), standard_version_id: sqlText('RACGP5'), indicator: sqlText(item.indicator), criterion: sqlText(item.criterion), criterion_description: sqlText(item.criterionDescription),
      classification: sqlText(item.classification), classification_source: sqlText(item.classificationSource), plain_english_requirement: sqlText(item.plainEnglishRequirement), applicability_rule: sqlText(item.applicability),
      primary_readiness_question: sqlText(item.primaryReadinessQuestion), assessment_basis: sqlText(item.assessmentBasis), appears_ready_rule: sqlText(item.rules?.appearsReady), needs_attention_rule: sqlText(item.rules?.needsAttention),
      confirmed_gap_rule: sqlText(item.rules?.confirmedGap), not_checked_rule: sqlText(item.rules?.notChecked), quick_check_priority: sqlText(item.quickCheckPriority), critical_safety_area: sqlBool(item.criticalSafetyArea),
      national_not_met_count: sqlNumber(item.nationalNotMetCount), national_not_met_rank: sqlNumber(item.nationalNotMetRank), content_validation_status: sqlText(item.contentValidationStatus), content_validation_source: sqlText(item.contentValidationSource),
      source_urls: sqlJson(item.sources || {}), source_payload: sqlJson(item), is_active: sqlBool(item.active),
    })),
    `on conflict (id) do update set standard_version_id=excluded.standard_version_id,indicator=excluded.indicator,criterion=excluded.criterion,criterion_description=excluded.criterion_description,classification=excluded.classification,classification_source=excluded.classification_source,plain_english_requirement=excluded.plain_english_requirement,applicability_rule=excluded.applicability_rule,primary_readiness_question=excluded.primary_readiness_question,assessment_basis=excluded.assessment_basis,appears_ready_rule=excluded.appears_ready_rule,needs_attention_rule=excluded.needs_attention_rule,confirmed_gap_rule=excluded.confirmed_gap_rule,not_checked_rule=excluded.not_checked_rule,quick_check_priority=excluded.quick_check_priority,critical_safety_area=excluded.critical_safety_area,national_not_met_count=excluded.national_not_met_count,national_not_met_rank=excluded.national_not_met_rank,content_validation_status=excluded.content_validation_status,content_validation_source=excluded.content_validation_source,source_urls=excluded.source_urls,source_payload=excluded.source_payload,is_active=excluded.is_active,updated_at=now()`
  ))

  chunks.push(valuesStatement('accreditation_questions',
    ['id','requirement_id','purpose','wording','show_rule','contextualisation_rule','evidence_prompt','clarification_template','why_we_ask','asked_because','quick_check_priority','validation_status','validation_source','is_active'],
    questions.map((item) => ({
      id: sqlText(item.id), requirement_id: sqlText(item.requirementId), purpose: sqlText(item.purpose), wording: sqlText(item.wording), show_rule: sqlText(item.showRule), contextualisation_rule: sqlText(item.contextualisationRule),
      evidence_prompt: sqlText(item.evidencePrompt), clarification_template: sqlText(item.clarificationTemplate), why_we_ask: sqlText(item.whyWeAsk), asked_because: sqlText(item.askedBecause), quick_check_priority: sqlText(item.quickCheckPriority),
      validation_status: sqlText(item.validationStatus), validation_source: sqlText(item.validationSource), is_active: sqlBool(item.validationStatus !== 'HOLD' && requirementActive.get(item.requirementId)),
    })),
    `on conflict (id) do update set requirement_id=excluded.requirement_id,purpose=excluded.purpose,wording=excluded.wording,show_rule=excluded.show_rule,contextualisation_rule=excluded.contextualisation_rule,evidence_prompt=excluded.evidence_prompt,clarification_template=excluded.clarification_template,why_we_ask=excluded.why_we_ask,asked_because=excluded.asked_because,quick_check_priority=excluded.quick_check_priority,validation_status=excluded.validation_status,validation_source=excluded.validation_source,is_active=excluded.is_active,updated_at=now()`
  ))

  chunks.push(valuesStatement('accreditation_answer_options',
    ['question_id','option_order','label','option_type','default_branch_behaviour'],
    answerOptions.map((item) => ({question_id:sqlText(item.questionId),option_order:sqlNumber(item.order),label:sqlText(item.label),option_type:sqlText(item.type),default_branch_behaviour:sqlText(item.defaultBranchBehaviour)})),
    `on conflict (question_id, option_order) do update set label=excluded.label,option_type=excluded.option_type,default_branch_behaviour=excluded.default_branch_behaviour`
  ))

  chunks.push(valuesStatement('accreditation_branching_rules',
    ['question_id','branch_order','requirement_id','trigger','follow_up_wording','suppression_rule'],
    branchingRules.map((item) => ({question_id:sqlText(item.questionId),branch_order:sqlNumber(item.order),requirement_id:sqlText(item.requirementId),trigger:sqlText(item.trigger),follow_up_wording:sqlText(item.followUpWording),suppression_rule:sqlText(item.suppressionRule)})),
    `on conflict (question_id, branch_order) do update set requirement_id=excluded.requirement_id,trigger=excluded.trigger,follow_up_wording=excluded.follow_up_wording,suppression_rule=excluded.suppression_rule`
  ))

  chunks.push(valuesStatement('accreditation_evidence_criteria',
    ['requirement_id','evidence_type','role','evidence_rule','assessment_dimensions'],
    evidenceCriteria.map((item) => ({requirement_id:sqlText(item.requirementId),evidence_type:sqlText(item.evidenceType),role:sqlText(item.role),evidence_rule:sqlText(item.evidenceRule),assessment_dimensions:sqlTextArray(item.assessmentDimensions)})),
    `on conflict (requirement_id, evidence_type) do update set role=excluded.role,evidence_rule=excluded.evidence_rule,assessment_dimensions=excluded.assessment_dimensions`
  ))

  chunks.push('\ncommit;\n')
  return chunks.filter(Boolean).join('\n')
}

async function main() {
  const [, , inputPath, outputPath] = process.argv
  if (!inputPath || !outputPath) throw new Error('Usage: node scripts/generate-accreditation-sql.mjs <dataset.json> <output.sql>')
  const dataset = JSON.parse(fs.readFileSync(path.resolve(inputPath), 'utf8'))
  const sql = generateAccreditationSql(dataset)
  const resolvedOutput = path.resolve(outputPath)
  fs.mkdirSync(path.dirname(resolvedOutput), { recursive: true })
  fs.writeFileSync(resolvedOutput, sql)
  console.log(`requirements=${dataset.requirements?.length || 0} questions=${dataset.questions?.length || 0} bytes=${Buffer.byteLength(sql)}`)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) main().catch((error) => { console.error(error.message); process.exitCode = 1 })